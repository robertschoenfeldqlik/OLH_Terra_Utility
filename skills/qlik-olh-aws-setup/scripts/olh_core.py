# --------------------------------------------------------------- helpers ----

def _err_has(e, *needles):
    s = str(e)
    return any(n in s for n in needles)


def _doc(x):
    """IAM may hand back a policy document percent-encoded; decode it with a regex (the sandbox blocks the URL-parsing module)."""
    if isinstance(x, str):
        x = json.loads(re.sub(r"%([0-9A-Fa-f]{2})", lambda m: chr(int(m.group(1), 16)), x))
    return x


def _norm(doc):
    """Normalise single-item Action/Resource lists so semantically equal docs compare equal."""
    def fix(v):
        if isinstance(v, list):
            v = [fix(i) for i in v]
            return v[0] if len(v) == 1 and not isinstance(v[0], dict) else v
        if isinstance(v, dict):
            return {k: fix(i) for k, i in v.items()}
        return v
    return json.dumps(fix(doc), sort_keys=True)


def _ctx(cfg, call, mode):
    # A plain dict, not a class: the AWS MCP sandbox has no __build_class__.
    return {"cfg": cfg, "call": call, "mode": mode, "region": cfg["region"],
            "actions": [], "out": {"region": cfg["region"]}, "writing": mode == "build"}


async def _aws(c, service, op, regional=True, **params):
    return await c["call"](service_name=service, operation_name=op,
                           region_name=c["region"] if regional else None, params=params)


def _note(c, obj, ident, action):
    c["actions"].append({"object": obj, "id": ident, "action": action})


