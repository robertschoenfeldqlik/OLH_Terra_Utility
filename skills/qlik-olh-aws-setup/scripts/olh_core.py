# ---------------------------------------------------------------- config ----

REQUIRED = ["prefix", "owner", "environment", "region", "vpc_cidr", "subnets",
            "qlik_proxy_role_arn", "qtc_external_id"]


def _validate(cfg):
    missing = [k for k in REQUIRED if not cfg.get(k)]
    if missing:
        raise ValueError("config is missing: " + ", ".join(missing))
    if len(cfg["subnets"]) < 2 or len({s["az"] for s in cfg["subnets"]}) < 2:
        raise ValueError("OLH needs at least two subnets in two different Availability Zones")
    for s in cfg["subnets"]:
        if not s["az"].startswith(cfg["region"]):
            raise ValueError(f"subnet AZ {s['az']} is not in region {cfg['region']}")
    if not re.match(r"^arn:aws[a-z-]*:iam::\d{12}:role/.+$", cfg["qlik_proxy_role_arn"]):
        raise ValueError("qlik_proxy_role_arn must be an IAM role ARN")


def names(cfg):
    p = cfg["prefix"]
    return {
        "vpc": f"{p}-vpc", "igw": f"{p}-igw", "rt": f"{p}-public-rt", "sg": f"{p}-sg",
        "vpce": f"{p}-s3-gateway-vpce", "kms_alias": f"alias/{p}-kms", "kms": f"{p}-kms",
        "mgmt_role": f"{p}-mgmt-role-iam", "node_role": f"{p}-ec2-role-iam",
        "profile": f"{p}-instance-profile", "stream": f"{p}-stream-kinesis",
        "mgmt_policy": "qlik-olh-management", "node_policy": "qlik-olh-ec2-instance",
    }


def subnet_name(cfg, az):
    return f"{cfg['prefix']}-public-{az[-1]}"


def bucket_names(cfg):
    kinds = ["config"] + [k for k in cfg.get("extra_buckets", ["iceberg", "landing"]) if k != "config"]
    return {k: f"{cfg['prefix']}-{k}-s3" for k in kinds}


def tag_pairs(cfg, name):
    return [
        ("Name", name),
        ("Owner", cfg["owner"]),
        ("Environment", cfg["environment"]),
        ("Workload", cfg["prefix"]),
        ("Application", "open-lakehouse"),
        ("CreateDate", cfg.get("create_date", "")),
        ("ManagedBy", cfg.get("managed_by", "qlik-olh-aws-setup")),
    ]


def tags_kv(cfg, name):
    return [{"Key": k, "Value": v} for k, v in tag_pairs(cfg, name)]


