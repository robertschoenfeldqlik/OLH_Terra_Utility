"""
Qlik Open Lakehouse on AWS - prerequisite builder, policy generator and verifier.

This is the sandbox-safe core. Two ways to run it:

  AWS MCP connector (aws___run_script):
      Pass this whole file as the script, followed by:
          CFG = {...}                                  # see config.example.json
          result = await run(CFG, call_boto3, "plan")  # or "build" / "verify"
          result
      The sandbox validates code statically before running it and rejects
      @property, getattr(), globals(), and imports of boto3, botocore, argparse
      and urllib - even in code that would never execute. At run time it has
      no class support (no __build_class__) and no botocore ClientError.
      Keep this file free of all of them; the boto3 adapter and CLI live in
      olh_build.py.

  Locally with boto3:
      python olh_build.py config.json --mode plan|build|verify [--out outputs.json]

Modes
  plan    read-only; reports, per object, whether it exists or would be created
  build   creates whatever is missing; every step is idempotent, so a re-run
          only re-asserts settings and never duplicates anything
  verify  read-only; re-reads every object by id and checks tags and settings

The Qlik-generated role policies below were captured verbatim from the
"Configuration guide" links on the Qlik Cloud "Create AWS network integration"
form (2026-10-22). Qlik can change them; references/troubleshooting.md says how
to re-check.
"""
