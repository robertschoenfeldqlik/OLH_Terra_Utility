async def _network(c):
    cfg, n = c["cfg"], names(c["cfg"])

    def ts(rtype, name):
        return [{"ResourceType": rtype, "Tags": tags_kv(cfg, name)}]

    v = await _aws(c, "ec2", "DescribeVpcs", Filters=[{"Name": "tag:Name", "Values": [n["vpc"]]}])
    if v["Vpcs"]:
        vpc = v["Vpcs"][0]["VpcId"]; _note(c, "VPC", vpc, "exists")
    elif c["writing"]:
        vpc = (await _aws(c, "ec2", "CreateVpc", CidrBlock=cfg["vpc_cidr"], TagSpecifications=ts("vpc", n["vpc"])))["Vpc"]["VpcId"]
        _note(c, "VPC", vpc, "created")
    else:
        _note(c, "VPC", n["vpc"], "would create")
        for obj in ("Internet gateway", "Route table", "Security group", "S3 gateway endpoint"):
            _note(c, obj, "-", "would create")
        for s in cfg["subnets"]:
            _note(c, "Subnet", subnet_name(cfg, s["az"]), "would create")
        return
    if c["writing"]:
        await _aws(c, "ec2", "ModifyVpcAttribute", VpcId=vpc, EnableDnsSupport={"Value": True})
        await _aws(c, "ec2", "ModifyVpcAttribute", VpcId=vpc, EnableDnsHostnames={"Value": True})
    c["out"]["vpc_id"], c["out"]["vpc_cidr"] = vpc, cfg["vpc_cidr"]

    ig = await _aws(c, "ec2", "DescribeInternetGateways", Filters=[{"Name": "attachment.vpc-id", "Values": [vpc]}])
    if ig["InternetGateways"]:
        igw = ig["InternetGateways"][0]["InternetGatewayId"]; _note(c, "Internet gateway", igw, "exists")
    elif c["writing"]:
        igw = (await _aws(c, "ec2", "CreateInternetGateway", TagSpecifications=ts("internet-gateway", n["igw"])))["InternetGateway"]["InternetGatewayId"]
        await _aws(c, "ec2", "AttachInternetGateway", InternetGatewayId=igw, VpcId=vpc)
        _note(c, "Internet gateway", igw, "created")
    else:
        igw = None; _note(c, "Internet gateway", n["igw"], "would create")

    rts = await _aws(c, "ec2", "DescribeRouteTables", Filters=[{"Name": "tag:Name", "Values": [n["rt"]]}, {"Name": "vpc-id", "Values": [vpc]}])
    if rts["RouteTables"]:
        rt = rts["RouteTables"][0]["RouteTableId"]; _note(c, "Route table", rt, "exists")
        has_default = any(r.get("DestinationCidrBlock") == "0.0.0.0/0" for r in rts["RouteTables"][0]["Routes"])
    elif c["writing"]:
        rt = (await _aws(c, "ec2", "CreateRouteTable", VpcId=vpc, TagSpecifications=ts("route-table", n["rt"])))["RouteTable"]["RouteTableId"]
        has_default = False; _note(c, "Route table", rt, "created")
    else:
        rt, has_default = None, True; _note(c, "Route table", n["rt"], "would create")
    if c["writing"] and not has_default:
        await _aws(c, "ec2", "CreateRoute", RouteTableId=rt, DestinationCidrBlock="0.0.0.0/0", GatewayId=igw)
    c["out"]["route_table_id"], c["out"]["igw_id"] = rt, igw

    subnets = []
    for s in cfg["subnets"]:
        name = subnet_name(cfg, s["az"])
        found = await _aws(c, "ec2", "DescribeSubnets", Filters=[{"Name": "tag:Name", "Values": [name]}, {"Name": "vpc-id", "Values": [vpc]}])
        if found["Subnets"]:
            sid = found["Subnets"][0]["SubnetId"]; _note(c, "Subnet", sid, "exists")
        elif c["writing"]:
            sid = (await _aws(c, "ec2", "CreateSubnet", VpcId=vpc, CidrBlock=s["cidr"], AvailabilityZone=s["az"],
                               TagSpecifications=ts("subnet", name)))["Subnet"]["SubnetId"]
            _note(c, "Subnet", sid, "created")
        else:
            _note(c, "Subnet", name, "would create"); continue
        if c["writing"]:
            # OLH cluster subnets must be public: auto-assign IP + IGW route.
            await _aws(c, "ec2", "ModifySubnetAttribute", SubnetId=sid, MapPublicIpOnLaunch={"Value": True})
            assoc = await _aws(c, "ec2", "DescribeRouteTables", Filters=[{"Name": "association.subnet-id", "Values": [sid]}])
            if not any(t["RouteTableId"] == rt for t in assoc["RouteTables"]):
                await _aws(c, "ec2", "AssociateRouteTable", RouteTableId=rt, SubnetId=sid)
        subnets.append({"subnet_id": sid, "az": s["az"], "cidr": s["cidr"]})
    c["out"]["subnets"] = subnets

    sg = await _aws(c, "ec2", "DescribeSecurityGroups", Filters=[{"Name": "group-name", "Values": [n["sg"]]}, {"Name": "vpc-id", "Values": [vpc]}])
    if sg["SecurityGroups"]:
        sgid = sg["SecurityGroups"][0]["GroupId"]; _note(c, "Security group", sgid, "exists")
        has_rule = any(p.get("IpProtocol") == "tcp" and p.get("FromPort") == 0 and p.get("ToPort") == 65535
                       and any(r.get("CidrIp") == cfg["vpc_cidr"] for r in p.get("IpRanges", []))
                       for p in sg["SecurityGroups"][0].get("IpPermissions", []))
    elif c["writing"]:
        sgid = (await _aws(c, "ec2", "CreateSecurityGroup", GroupName=n["sg"], Description=f"Qlik Open Lakehouse {cfg['prefix']}",
                            VpcId=vpc, TagSpecifications=ts("security-group", n["sg"])))["GroupId"]
        has_rule = False; _note(c, "Security group", sgid, "created")
    else:
        sgid, has_rule = None, True; _note(c, "Security group", n["sg"], "would create")
    if c["writing"] and not has_rule:
        await _aws(c, "ec2", "AuthorizeSecurityGroupIngress", GroupId=sgid, IpPermissions=[{
            "IpProtocol": "tcp", "FromPort": 0, "ToPort": 65535,
            "IpRanges": [{"CidrIp": cfg["vpc_cidr"], "Description": "OLH intra-VPC: cluster and network integration agent"}]}])
    c["out"]["security_group_id"] = sgid

    ep = await _aws(c, "ec2", "DescribeVpcEndpoints", Filters=[
        {"Name": "vpc-id", "Values": [vpc]}, {"Name": "service-name", "Values": [f"com.amazonaws.{c['region']}.s3"]},
        {"Name": "vpc-endpoint-type", "Values": ["Gateway"]}])
    live = [e for e in ep["VpcEndpoints"] if e.get("State") not in ("deleted", "deleting")]
    if live:
        vpce = live[0]["VpcEndpointId"]; _note(c, "S3 gateway endpoint", vpce, "exists")
    elif c["writing"]:
        vpce = (await _aws(c, "ec2", "CreateVpcEndpoint", VpcId=vpc, ServiceName=f"com.amazonaws.{c['region']}.s3",
                            VpcEndpointType="Gateway", RouteTableIds=[rt],
                            TagSpecifications=ts("vpc-endpoint", n["vpce"])))["VpcEndpoint"]["VpcEndpointId"]
        _note(c, "S3 gateway endpoint", vpce, "created")
    else:
        vpce = None; _note(c, "S3 gateway endpoint", n["vpce"], "would create")
    c["out"]["s3_gateway_endpoint_id"] = vpce


async def _kms(c):
    n = names(c["cfg"])
    al = await _aws(c, "kms", "ListAliases")
    hit = [a for a in al["Aliases"] if a["AliasName"] == n["kms_alias"] and a.get("TargetKeyId")]
    if hit:
        key = hit[0]["TargetKeyId"]; _note(c, "KMS key", n["kms_alias"], "exists")
    elif c["writing"]:
        k = await _aws(c, "kms", "CreateKey", Description=f"Qlik Open Lakehouse {c['cfg']['prefix']}",
                        KeyUsage="ENCRYPT_DECRYPT", KeySpec="SYMMETRIC_DEFAULT",
                        Tags=[{"TagKey": k, "TagValue": v} for k, v in tag_pairs(c["cfg"], n["kms"])])
        key = k["KeyMetadata"]["KeyId"]
        await _aws(c, "kms", "CreateAlias", AliasName=n["kms_alias"], TargetKeyId=key)
        _note(c, "KMS key", n["kms_alias"], "created")
    else:
        _note(c, "KMS key", n["kms_alias"], "would create"); c["out"]["kms_key_arn"] = None; return
    if c["writing"]:
        await _aws(c, "kms", "EnableKeyRotation", KeyId=key)
    c["out"]["kms_key_arn"] = (await _aws(c, "kms", "DescribeKey", KeyId=key))["KeyMetadata"]["Arn"]
    c["out"]["kms_alias"] = n["kms_alias"]


async def _service_linked_roles(c):
    # Qlik creates these itself on first deploy, but the Auto Scaling group is
    # created before the role is usable and the deploy fails with "The
    # Service-Linked Role for this Auto Scaling group is not yet ready for use".
    # Creating them up front removes the race.
    for svc, role in (("autoscaling.amazonaws.com", "AWSServiceRoleForAutoScaling"),
                      ("spot.amazonaws.com", "AWSServiceRoleForEC2Spot")):
        try:
            await _aws(c, "iam", "GetRole", regional=False, RoleName=role)
            _note(c, "Service-linked role", role, "exists")
        except Exception as e:
            if not _err_has(e, "NoSuchEntity"):
                raise
            if c["writing"]:
                await _aws(c, "iam", "CreateServiceLinkedRole", regional=False, AWSServiceName=svc)
                _note(c, "Service-linked role", role, "created")
            else:
                _note(c, "Service-linked role", role, "would create")


async def _role(c, role, trust, label, description):
    try:
        r = await _aws(c, "iam", "GetRole", regional=False, RoleName=role)
        if c["writing"]:
            await _aws(c, "iam", "UpdateAssumeRolePolicy", regional=False, RoleName=role, PolicyDocument=json.dumps(trust))
        _note(c, label, role, "exists")
        return r["Role"]["Arn"]
    except Exception as e:
        if not _err_has(e, "NoSuchEntity"):
            raise
    if not c["writing"]:
        _note(c, label, role, "would create"); return None
    r = await _aws(c, "iam", "CreateRole", regional=False, RoleName=role, AssumeRolePolicyDocument=json.dumps(trust),
                    Description=description, Tags=tags_kv(c["cfg"], role))
    _note(c, label, role, "created")
    return r["Role"]["Arn"]


async def _iam(c):
    cfg, n = c["cfg"], names(c["cfg"])
    c["out"]["mgmt_role_arn"] = await _role(c, n["mgmt_role"], mgmt_trust_policy(cfg), "Management role",
                                         f"Qlik Talend Cloud management role for {cfg['prefix']}")
    c["out"]["node_role_arn"] = await _role(c, n["node_role"], NODE_TRUST, "Node role",
                                         f"Qlik Open Lakehouse EC2 node role for {cfg['prefix']}")
    if c["writing"]:
        await _aws(c, "iam", "AttachRolePolicy", regional=False, RoleName=n["node_role"],
                    PolicyArn="arn:aws:iam::aws:policy/AmazonSSMManagedInstanceCore")
    try:
        ip = await _aws(c, "iam", "GetInstanceProfile", regional=False, InstanceProfileName=n["profile"])
        _note(c, "Instance profile", n["profile"], "exists")
    except Exception as e:
        if not _err_has(e, "NoSuchEntity"):
            raise
        if not c["writing"]:
            _note(c, "Instance profile", n["profile"], "would create"); c["out"]["instance_profile_arn"] = None; return
        ip = await _aws(c, "iam", "CreateInstanceProfile", regional=False, InstanceProfileName=n["profile"],
                         Tags=tags_kv(cfg, n["profile"]))
        _note(c, "Instance profile", n["profile"], "created")
    if c["writing"] and n["node_role"] not in [r["RoleName"] for r in ip["InstanceProfile"].get("Roles", [])]:
        await _aws(c, "iam", "AddRoleToInstanceProfile", regional=False, InstanceProfileName=n["profile"], RoleName=n["node_role"])
    c["out"]["instance_profile_arn"] = ip["InstanceProfile"]["Arn"]


async def _buckets(c):
    cfg, kms = c["cfg"], c["out"].get("kms_key_arn")
    sse = {"Rules": [{"ApplyServerSideEncryptionByDefault": {"SSEAlgorithm": "aws:kms", "KMSMasterKeyID": kms},
                      "BucketKeyEnabled": True}]}
    pab = {"BlockPublicAcls": True, "IgnorePublicAcls": True, "BlockPublicPolicy": True, "RestrictPublicBuckets": True}
    out = {}
    for kind, b in bucket_names(cfg).items():
        try:
            await _aws(c, "s3", "HeadBucket", Bucket=b); state = "exists"
        except Exception as e:
            if _err_has(e, "404", "Not Found", "NoSuchBucket"):
                state = "free"
            else:
                raise RuntimeError(f"bucket name {b} is owned by another account or not accessible: {e}")
        if state == "free" and not c["writing"]:
            _note(c, "S3 bucket", b, "would create"); out[kind] = b; continue
        if state == "free":
            params = {"Bucket": b}
            if c["region"] != "us-east-1":
                params["CreateBucketConfiguration"] = {"LocationConstraint": c["region"]}
            await _aws(c, "s3", "CreateBucket", **params)
            _note(c, "S3 bucket", b, "created")
        else:
            _note(c, "S3 bucket", b, "exists")
        if c["writing"]:
            await _aws(c, "s3", "PutBucketEncryption", Bucket=b, ServerSideEncryptionConfiguration=sse)
            await _aws(c, "s3", "PutPublicAccessBlock", Bucket=b, PublicAccessBlockConfiguration=pab)
            await _aws(c, "s3", "PutBucketTagging", Bucket=b, Tagging={"TagSet": tags_kv(cfg, b)})
            if kind == "tfstate":
                await _aws(c, "s3", "PutBucketVersioning", Bucket=b, VersioningConfiguration={"Status": "Enabled"})
        out[kind] = b
    c["out"]["buckets"] = out


async def _inline_policies(c):
    n = names(c["cfg"])
    kms, acct = c["out"].get("kms_key_arn"), c["out"]["account_id"]
    if not kms or not c["out"].get("mgmt_role_arn"):
        _note(c, "Qlik inline policies", "-", "would attach"); return
    docs = {
        n["mgmt_role"]: (n["mgmt_policy"], mgmt_inline_policy(acct, kms)),
        n["node_role"]: (n["node_policy"], node_inline_policy(kms, c["out"]["buckets"]["config"], c["cfg"]["qtc_external_id"])),
    }
    for role, (pname, doc) in docs.items():
        try:
            cur = _doc((await _aws(c, "iam", "GetRolePolicy", regional=False, RoleName=role, PolicyName=pname))["PolicyDocument"])
            same = _norm(cur) == _norm(doc)
        except Exception as e:
            if not _err_has(e, "NoSuchEntity"):
                raise
            same = None
        if same:
            _note(c, "Qlik inline policy", f"{role}:{pname}", "exists, matches")
        elif c["writing"]:
            await _aws(c, "iam", "PutRolePolicy", regional=False, RoleName=role, PolicyName=pname, PolicyDocument=json.dumps(doc))
            _note(c, "Qlik inline policy", f"{role}:{pname}", "attached" if same is None else "updated")
        else:
            _note(c, "Qlik inline policy", f"{role}:{pname}", "would attach" if same is None else "would update")


async def _kinesis(c):
    if not c["cfg"].get("create_kinesis"):
        return
    stream = names(c["cfg"])["stream"]
    try:
        d = await _aws(c, "kinesis", "DescribeStreamSummary", StreamName=stream)
        _note(c, "Kinesis stream", stream, "exists")
    except Exception as e:
        if not _err_has(e, "ResourceNotFoundException"):
            raise
        if not c["writing"]:
            _note(c, "Kinesis stream", stream, "would create"); return
        # One provisioned shard is the cheapest setting (on-demand has a higher floor).
        await _aws(c, "kinesis", "CreateStream", StreamName=stream, ShardCount=1, StreamModeDetails={"StreamMode": "PROVISIONED"})
        _note(c, "Kinesis stream", stream, "created")
        for _ in range(30):
            d = await _aws(c, "kinesis", "DescribeStreamSummary", StreamName=stream)
            if d["StreamDescriptionSummary"]["StreamStatus"] == "ACTIVE":
                break
            await asyncio.sleep(4)
        await _aws(c, "kinesis", "AddTagsToStream", StreamName=stream, Tags=dict(tag_pairs(c["cfg"], stream)))
    c["out"]["kinesis_stream_arn"] = d["StreamDescriptionSummary"]["StreamARN"]


async def _build(c):
    c["out"]["account_id"] = (await _aws(c, "sts", "GetCallerIdentity", regional=False))["Account"]
    await _service_linked_roles(c)
    await _network(c)
    await _kms(c)
    await _iam(c)
    await _buckets(c)
    await _inline_policies(c)
    await _kinesis(c)


# ---------------------------------------------------------------- verify ----

async def _verify(c):
    cfg, n = c["cfg"], names(c["cfg"])
    rows = []

    def check(obj, ident, tags, name, detail, ok=True, key="Key", val="Value"):
        t = {x[key]: x[val] for x in (tags or [])}
        want = dict(tag_pairs(cfg, name))
        want.pop("CreateDate", None)
        bad = [k for k, v in want.items() if t.get(k) != v]
        rows.append({"object": obj, "id": ident, "ok": ok and not bad,
                     "tag_problems": bad, "detail": detail})

    c["out"]["account_id"] = (await _aws(c, "sts", "GetCallerIdentity", regional=False))["Account"]
    v = await _aws(c, "ec2", "DescribeVpcs", Filters=[{"Name": "tag:Name", "Values": [n["vpc"]]}])
    if not v["Vpcs"]:
        return {"ok": False, "rows": [{"object": "VPC", "ok": False, "detail": f"{n['vpc']} not found - run build first"}]}
    vpc = v["Vpcs"][0]
    check("VPC", vpc["VpcId"], vpc.get("Tags"), n["vpc"], f"cidr={vpc['CidrBlock']}", vpc["CidrBlock"] == cfg["vpc_cidr"])

    rt = (await _aws(c, "ec2", "DescribeRouteTables", Filters=[{"Name": "tag:Name", "Values": [n["rt"]]}]))["RouteTables"][0]
    to_igw = any(r.get("DestinationCidrBlock") == "0.0.0.0/0" and r.get("GatewayId", "").startswith("igw-") for r in rt["Routes"])
    to_vpce = any(r.get("GatewayId", "").startswith("vpce-") for r in rt["Routes"])
    check("Route table", rt["RouteTableId"], rt.get("Tags"), n["rt"], f"0.0.0.0/0->igw={to_igw} s3-endpoint-route={to_vpce}", to_igw and to_vpce)

    subs = await _aws(c, "ec2", "DescribeSubnets", Filters=[{"Name": "vpc-id", "Values": [vpc["VpcId"]]}])
    assoc = {a.get("SubnetId") for a in rt["Associations"]}
    for s in subs["Subnets"]:
        check("Subnet", s["SubnetId"], s.get("Tags"), subnet_name(cfg, s["AvailabilityZone"]),
              f"az={s['AvailabilityZone']} public_ip={s['MapPublicIpOnLaunch']} routed={s['SubnetId'] in assoc}",
              s["MapPublicIpOnLaunch"] and s["SubnetId"] in assoc)

    sg = (await _aws(c, "ec2", "DescribeSecurityGroups", Filters=[{"Name": "group-name", "Values": [n["sg"]]}, {"Name": "vpc-id", "Values": [vpc["VpcId"]]}]))["SecurityGroups"][0]
    rule = any(p.get("IpProtocol") == "tcp" and p.get("FromPort") == 0 and p.get("ToPort") == 65535
               and any(r.get("CidrIp") == cfg["vpc_cidr"] for r in p.get("IpRanges", [])) for p in sg["IpPermissions"])
    check("Security group", sg["GroupId"], sg.get("Tags"), n["sg"], f"all-TCP-from-VPC={rule}", rule)

    al = [a for a in (await _aws(c, "kms", "ListAliases"))["Aliases"] if a["AliasName"] == n["kms_alias"]]
    key = al[0]["TargetKeyId"]
    km = (await _aws(c, "kms", "DescribeKey", KeyId=key))["KeyMetadata"]
    rot = (await _aws(c, "kms", "GetKeyRotationStatus", KeyId=key))["KeyRotationEnabled"]
    check("KMS key", km["Arn"], (await _aws(c, "kms", "ListResourceTags", KeyId=key))["Tags"], n["kms"],
          f"state={km['KeyState']} rotation={rot}", km["KeyState"] == "Enabled", "TagKey", "TagValue")

    mg = (await _aws(c, "iam", "GetRole", regional=False, RoleName=n["mgmt_role"]))["Role"]
    trust_ok = _norm(_doc(mg["AssumeRolePolicyDocument"])) == _norm(mgmt_trust_policy(cfg))
    check("Management role", mg["Arn"], mg.get("Tags"), n["mgmt_role"], f"trust_matches_trust_entity={trust_ok}", trust_ok)
    nr = (await _aws(c, "iam", "GetRole", regional=False, RoleName=n["node_role"]))["Role"]
    check("Node role", nr["Arn"], nr.get("Tags"), n["node_role"], "ec2.amazonaws.com trust")
    ip = (await _aws(c, "iam", "GetInstanceProfile", regional=False, InstanceProfileName=n["profile"]))["InstanceProfile"]
    has_node = n["node_role"] in [r["RoleName"] for r in ip["Roles"]]
    check("Instance profile", ip["Arn"], ip.get("Tags"), n["profile"], f"holds_node_role={has_node}", has_node)

    buckets = bucket_names(cfg)
    for role, pname, doc in ((n["mgmt_role"], n["mgmt_policy"], mgmt_inline_policy(c["out"]["account_id"], km["Arn"])),
                             (n["node_role"], n["node_policy"], node_inline_policy(km["Arn"], buckets["config"], cfg["qtc_external_id"]))):
        try:
            cur = _doc((await _aws(c, "iam", "GetRolePolicy", regional=False, RoleName=role, PolicyName=pname))["PolicyDocument"])
            same = _norm(cur) == _norm(doc)
        except Exception:
            same = False
        rows.append({"object": "Qlik inline policy", "id": f"{role}:{pname}", "ok": same, "tag_problems": [],
                     "detail": "matches the Qlik-generated policy" if same else "missing or different"})

    for role in ("AWSServiceRoleForAutoScaling", "AWSServiceRoleForEC2Spot"):
        try:
            await _aws(c, "iam", "GetRole", regional=False, RoleName=role); ok = True
        except Exception:
            ok = False
        rows.append({"object": "Service-linked role", "id": role, "ok": ok, "tag_problems": [], "detail": "present" if ok else "MISSING"})

    for kind, b in buckets.items():
        rule0 = (await _aws(c, "s3", "GetBucketEncryption", Bucket=b))["ServerSideEncryptionConfiguration"]["Rules"][0]
        on_cmk = rule0["ApplyServerSideEncryptionByDefault"].get("KMSMasterKeyID") == km["Arn"]
        pab = all((await _aws(c, "s3", "GetPublicAccessBlock", Bucket=b))["PublicAccessBlockConfiguration"].values())
        check("S3 bucket", b, (await _aws(c, "s3", "GetBucketTagging", Bucket=b))["TagSet"], b,
              f"cmk={on_cmk} public_blocked={pab}", on_cmk and pab)

    return {"ok": all(r["ok"] for r in rows), "rows": rows}


# ------------------------------------------------------------- entrypoint ----

async def run(cfg, call, mode="plan"):
    """mode: plan | build | verify. `call` is call_boto3 (AWS MCP) or the boto3 adapter in olh_build.py."""
    _validate(cfg)
    if not cfg.get("create_date"):
        cfg = dict(cfg, create_date=datetime.date.today().isoformat())
    c = _ctx(cfg, call, mode)
    if mode == "verify":
        return await _verify(c)
    if mode not in ("plan", "build"):
        raise ValueError("mode must be plan, build or verify")
    await _build(c)
    return {"mode": mode, "actions": c["actions"], "outputs": c["out"]}
